"use client";

import { Suspense, useEffect, useState } from "react";
import Link from "next/link";
import { useParams } from "next/navigation";
import { decodeShareSlug, type SharePayload } from "@/lib/share";
import Board from "@/components/Board";
import TranscriptPanel from "@/components/TranscriptPanel";

function ShareViewInner() {
  const params = useParams<{ slug: string }>();
  const slug = params?.slug ?? "";
  const [payload, setPayload] = useState<SharePayload | null>(null);
  const [error, setError] = useState(false);
  const [selectedSeg, setSelectedSeg] = useState<number | null>(null);

  useEffect(() => {
    if (!slug) return;
    let cancelled = false;
    decodeShareSlug(slug)
      .then((p) => {
        if (!cancelled) setPayload(p);
      })
      .catch(() => {
        if (!cancelled) setError(true);
      });
    return () => {
      cancelled = true;
    };
  }, [slug]);

  if (error) {
    return (
      <div className="mx-auto flex w-full max-w-[768px] flex-col items-start gap-4 px-4 py-10">
        <p className="text-sm text-zinc-500 dark:text-zinc-400">
          This link is malformed or was generated by an older version.
        </p>
        <Link
          href="/"
          className="text-sm font-medium text-emerald-600 hover:underline dark:text-emerald-400 print:hidden"
        >
          Make your own board
        </Link>
      </div>
    );
  }

  if (!payload) {
    return (
      <div className="mx-auto flex w-full max-w-[768px] flex-col gap-4 px-4 py-10" aria-busy="true">
        <div className="h-7 w-56 animate-pulse rounded bg-zinc-200 dark:bg-zinc-800" />
        <div className="h-4 w-full animate-pulse rounded bg-zinc-200 dark:bg-zinc-800" />
        <div className="h-4 w-3/4 animate-pulse rounded bg-zinc-200 dark:bg-zinc-800" />
        <div className="h-24 w-full animate-pulse rounded bg-zinc-200 dark:bg-zinc-800" />
        <div className="h-16 w-full animate-pulse rounded bg-zinc-200 dark:bg-zinc-800" />
      </div>
    );
  }

  return (
    <div className="mx-auto flex w-full max-w-[768px] flex-col gap-6 px-4 py-10">
      <header>
        <h1 className="text-2xl font-semibold tracking-tight text-zinc-900 dark:text-zinc-50">
          {payload.meta.title ?? "Decision board"}
        </h1>
        <p className="text-sm text-zinc-500 dark:text-zinc-400">
          Read-only shared board.
        </p>
      </header>

      <Board
        extracted={payload.extracted}
        meta={payload.meta}
        segments={payload.transcript.segments}
        onSelect={setSelectedSeg}
        editable={false}
        onChange={() => {}}
      />

      <TranscriptPanel
        segments={payload.transcript.segments}
        selectedSeg={selectedSeg}
        onSelect={setSelectedSeg}
        withAudio={false}
      />

      {payload.transcript.truncated && (
        <p className="text-xs text-zinc-400 dark:text-zinc-500">
          Transcript shortened to fit the link.
        </p>
      )}

      <footer className="mt-2 flex flex-col gap-2 text-xs text-zinc-400 dark:text-zinc-500">
        <span className="print:hidden">Made with NoHands Log</span>
        <Link
          href="/"
          className="font-medium text-emerald-600 hover:underline dark:text-emerald-400 print:hidden"
        >
          Make your own board
        </Link>
      </footer>
    </div>
  );
}

export default function ShareView() {
  return (
    <Suspense
      fallback={
        <div className="mx-auto flex w-full max-w-[768px] flex-col gap-4 px-4 py-10">
          <div className="h-7 w-56 animate-pulse rounded bg-zinc-200 dark:bg-zinc-800" />
        </div>
      }
    >
      <ShareViewInner />
    </Suspense>
  );
}
