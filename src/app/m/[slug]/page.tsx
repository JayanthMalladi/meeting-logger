"use client";

import { useEffect, useMemo, useState, Suspense } from "react";
import { useParams } from "next/navigation";
import { decodeShareSlug } from "@/lib/share";
import Board from "@/components/Board";

function ShareViewInner() {
  const params = useParams<{ slug: string }>();
  const [error, setError] = useState<string | null>(null);

  const payload = useMemo(() => {
    if (!params?.slug) return null;
    try {
      return decodeShareSlug(params.slug);
    } catch {
      setError("This link is malformed or was generated by an older version.");
      return null;
    }
  }, [params?.slug]);

  useEffect(() => {
    if (payload?.transcript.truncated) {
      // no-op — board still renders; we just note it in UI
    }
  }, [payload]);

  return (
    <div className="mx-auto flex w-full max-w-3xl flex-col gap-6 px-4 py-10">
      <header>
        <h1 className="text-2xl font-semibold tracking-tight">Decision board</h1>
        <p className="text-sm text-zinc-500 dark:text-zinc-400">
          A zero-signup, read-only view.{" "}
          {payload?.transcript.truncated
            ? "Transcript in this link is truncated to keep the URL openable."
            : null}
        </p>
      </header>
      {error ? (
        <p className="rounded-lg bg-amber-50 p-4 text-sm text-amber-900 dark:bg-amber-950/40 dark:text-amber-200">
          {error}
        </p>
      ) : payload ? (
        <>
          <Board extracted={payload.extracted} meta={payload.meta} />
          {payload.transcript.segments.length > 0 && (
            <p className="text-xs text-zinc-400">
              {payload.transcript.segments.length} transcript segments
              {payload.transcript.truncated ? " (truncated)" : ""}
            </p>
          )}
        </>
      ) : (
        !error && <p className="text-sm text-zinc-500">Loading…</p>
      )}
      <footer className="mt-4 text-xs text-zinc-400 dark:text-zinc-500">
        Made with NoHands Log
      </footer>
    </div>
  );
}

export default function ShareView() {
  return (
    <Suspense fallback={<p className="px-4 py-10 text-sm text-zinc-500">Loading…</p>}>
      <ShareViewInner />
    </Suspense>
  );
}
